-- В магазине оставляем только 8 инструментов из стартового каталога.
-- Товары мастеров (master_id не пустой) не трогаем.
-- Не удаляем, чтобы не сломать старые заказы/корзины — просто скрываем.
UPDATE public.shop_products
SET is_approved = false,
    in_stock = false,
    is_popular = false
WHERE master_id IS NULL
  AND name NOT IN ('Болгарка', 'Шуруповерт', 'Лобзик', 'Лазерный уровень',
                   'Набор ключей', 'Набор отверток', 'Рулетка 5м', 'Молоток');

-- На случай если какой-то из 8 был скрыт раньше — делаем видимым.
UPDATE public.shop_products
SET is_approved = true
WHERE master_id IS NULL
  AND name IN ('Болгарка', 'Шуруповерт', 'Лобзик', 'Лазерный уровень',
               'Набор ключей', 'Набор отверток', 'Рулетка 5м', 'Молоток');
